import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { obtenerDatosAprobacionesPresentacion } from "./datos-presentacion.js";
import { MENSAJES_APROBACIONES_ES, crearTraductorAprobaciones } from "./i18n.js";

const datos = obtenerDatosAprobacionesPresentacion();
assert.equal(datos.estado, "visual_pendiente_backend");
assert.equal(datos.aviso, "Datos ficticios de presentación");
assert.equal(datos.pendientes.length, 4);
assert.ok(datos.pendientes.every((item) => item.documentos.length > 0 && item.revisiones.length > 0 && item.autoridad.length > 0));
const vista = await readFile(new URL("./vista.js", import.meta.url), "utf8");
const css = await readFile(new URL("./aprobaciones.css", import.meta.url), "utf8");
assert.match(vista, /export function montarVistaAprobaciones/);
assert.match(vista, /renderizarEstadoEntrega/);
assert.match(vista, /disabled = true/);
assert.doesNotMatch(vista, /fetch\(|localStorage|sessionStorage|indexedDB|document\.cookie/);
const clavesUsadas = [...vista.matchAll(/t\("([a-z_]+)"/gu)].map((resultado) => resultado[1]);
assert.ok(clavesUsadas.length > 25);
assert.ok(clavesUsadas.every((clave) => Object.hasOwn(MENSAJES_APROBACIONES_ES, clave)));
assert.equal(crearTraductorAprobaciones()("recibo", { referencia: "REC-APR-SINT-0148" }), "Recibo visual: REC-APR-SINT-0148. La auditoría durable no está conectada.");
assert.equal(crearTraductorAprobaciones()("acciones"), "Acciones");
assert.equal(crearTraductorAprobaciones()("unidad"), "Unidad");
assert.doesNotMatch(vista, /\["referencia"[^\]]*,\s*""\]\.map\(t\)/u);
assert.match(vista, /crear\(d, "dl", "", "aprobaciones-resumen"\)/u);
assert.match(vista, /crear\(d, "section", "", "panel aprobaciones-suplencias"\)/u);
assert.throws(() => crearTraductorAprobaciones()("clave_inexistente"), /no definida/);
assert.match(css, /\.aprobaciones-principal\{[^}]*grid-template-columns:minmax\(0,1\.45fr\) minmax\(0,\.9fr\)[^}]*min-width:0/);
assert.match(css, /\.aprobaciones-tabla\{[^}]*width:100%[^}]*min-width:0[^}]*overflow-x:auto/);
assert.match(css, /\.aprobaciones-tabla table\{width:max-content;min-width:100%/);
assert.match(css, /@media\(max-width:520px\)\{[^}]*\.aprobaciones-filtros[^}]*grid-template-columns:minmax\(0,1fr\)/);
console.log("aprobaciones presentation tests: ok");
