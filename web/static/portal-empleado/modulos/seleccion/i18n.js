const CLAVES = new Set(Object.keys(MENSAJES_SELECCION_ES));

export function crearTraductorSeleccion(catalogo = MENSAJES_SELECCION_ES) {
  return (clave, variables = {}) => {
    if (!CLAVES.has(clave)) throw new TypeError(`clave i18n de Selección desconocida: ${clave}`);
    const texto = typeof catalogo[clave] === "string" ? catalogo[clave] : MENSAJES_SELECCION_ES[clave];
    return texto.replace(/\{([a-z_]+)\}/gu, (_c, nombre) => String(variables[nombre] ?? ""));
  };
}

export function textoErrorSeleccion(t, codigo) {
  return CLAVES.has(`error_${codigo}`) ? t(`error_${codigo}`) : t("error_respuesta_incompatible");
}
