export function crearTraductorInscripciones(catalogo = MENSAJES_INSCRIPCIONES_ES) {
  if (!catalogo || Object.keys(MENSAJES_INSCRIPCIONES_ES).some((clave) => typeof catalogo[clave] !== "string" || !catalogo[clave])) throw new TypeError("catálogo de inscripciones incompleto");
  return (clave) => {
    if (!Object.hasOwn(MENSAJES_INSCRIPCIONES_ES, clave)) throw new TypeError(`clave de inscripciones desconocida: ${clave}`);
    return catalogo[clave];
  };
}
