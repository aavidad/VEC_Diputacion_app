const CLAVES = new Set(Object.keys(MENSAJES_SOLICITUD_ES));

export function crearTraductorSolicitud(catalogo = MENSAJES_SOLICITUD_ES) {
  return (clave, variables = {}) => {
    if (!CLAVES.has(clave)) throw new TypeError(`clave i18n de solicitud desconocida: ${clave}`);
    const texto = typeof catalogo[clave] === "string" ? catalogo[clave] : MENSAJES_SOLICITUD_ES[clave];
    return texto.replace(/\{([a-z_]+)\}/gu, (_c, nombre) => String(variables[nombre] ?? ""));
  };
}

/** Mensaje del catálogo para un código de error del adaptador. */
export function textoErrorSolicitud(t, codigo) {
  const clave = `error_${codigo}`;
  return CLAVES.has(clave) ? t(clave) : t("error_respuesta_incompatible");
}
