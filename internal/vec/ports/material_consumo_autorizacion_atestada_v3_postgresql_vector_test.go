func TestVectorPostgreSQLHuellaMaterialConsumoV3(t *testing.T) {
	t.Parallel()
	emitida := time.Date(2026, 7, 28, 8, 9, 10, 123456000, time.UTC)
	expira := emitida.Add(4 * time.Second)
	resumen, err := NuevoResumenCapacidadAtestacionAutorizacionV3(
		"decision:rrhh:vector-pg",
		string(bytes.Repeat([]byte{'3'}, 64)),
		string(bytes.Repeat([]byte{'4'}, 64)),
		"contexto:rrhh:vector-pg",
		string(bytes.Repeat([]byte{'8'}, 64)),
		"contratacion_temporal.consultar_cuadro_rrhh",
		"consulta:rrhh:vector-pg",
		string(bytes.Repeat([]byte{'9'}, 64)),
		"vec_contratacion_temporal.consultar_cuadro_rrhh.v3",
		emitida,
		expira,
	)
	if err != nil {
		t.Fatal(err)
	}
	privada := ed25519.NewKeyFromSeed(bytes.Repeat([]byte{0x42}, 32))
	spki, err := x509.MarshalPKIXPublicKey(privada.Public())
	if err != nil {
		t.Fatal(err)
	}
	if obtenido := hex.EncodeToString(spki); obtenido != spkiMaterialPostgreSQLV3Hex {
		t.Fatalf("SPKI del vector material cambió: %s", obtenido)
	}
	preimagen := preimagenMaterialPostgreSQLV3(resumen, spki)
	if obtenido := hex.EncodeToString(preimagen); obtenido != preimagenMaterialPostgreSQLV3Hex {
		t.Fatalf("preimagen material PostgreSQL cambió: %s", obtenido)
	}
	sumaPreimagen := sha256.Sum256(preimagen)
	if hex.EncodeToString(sumaPreimagen[:]) != huellaMaterialPostgreSQLV3 {
		t.Fatal("preimagen externa no corresponde a su huella congelada")
	}
	exportacion, err := NuevaExportacionMaterialConsumoAutorizacionAtestadaV3(
		[]byte(capacidadCanonicaPostgreSQLV3),
		resumen,
		[]byte("decision-canonica-vector-pg"),
		[]byte("motivo-canonico-vector-pg"),
		[]byte("contexto-actor-canonico-vector-pg"),
		7,
		11,
		[]byte("payload-vec-ad-3-vector-pg"),
		[]byte("sobre-cose-sign1-vector-pg"),
		[]byte("evidencia-verificacion-vector-pg"),
		spki,
	)
	if err != nil {
		t.Fatal(err)
	}
	huella, err := exportacion.HuellaConjuntoSHA256()
	if err != nil {
		t.Fatal(err)
	}
	if huella != huellaMaterialPostgreSQLV3 {
		t.Fatalf("vector material PostgreSQL cambió: %s", huella)
	}
}

func preimagenMaterialPostgreSQLV3(
	resumen ResumenCapacidadAtestacionAutorizacionV3,
	spki []byte,
) []byte {
	var preimagen []byte
	bloque := func(contenido []byte) {
		var longitud [8]byte
		binary.BigEndian.PutUint64(longitud[:], uint64(len(contenido)))
		preimagen = append(preimagen, longitud[:]...)
		preimagen = append(preimagen, contenido...)
	}
	for _, contenido := range [][]byte{
		[]byte(capacidadCanonicaPostgreSQLV3),
		[]byte(resumen.DecisionRef()),
		[]byte(resumen.DecisionHuellaSHA256()),
		[]byte(resumen.MotivoHuellaSHA256()),
		[]byte(resumen.ContextoRef()),
		[]byte(resumen.ContextoHuellaSHA256()),
		[]byte(resumen.Operacion()),
		[]byte(resumen.EfectoRef()),
		[]byte(resumen.EfectoHuellaSHA256()),
		[]byte(resumen.AudienciaConsumo()),
		[]byte(resumen.EmitidaEn().Format(time.RFC3339Nano)),
		[]byte(resumen.ExpiraEn().Format(time.RFC3339Nano)),
		[]byte("decision-canonica-vector-pg"),
		[]byte("motivo-canonico-vector-pg"),
		[]byte("contexto-actor-canonico-vector-pg"),
	} {
		bloque(contenido)
	}
	var version [8]byte
	binary.BigEndian.PutUint64(version[:], 7)
	bloque(version[:])
	binary.BigEndian.PutUint64(version[:], 11)
	bloque(version[:])
	for _, contenido := range [][]byte{
		[]byte("payload-vec-ad-3-vector-pg"),
		[]byte("sobre-cose-sign1-vector-pg"),
		[]byte("evidencia-verificacion-vector-pg"),
		spki,
	} {
		bloque(contenido)
	}
	return preimagen
}

func TestVectorPostgreSQLPreimagenMaterialV3LigaSusVeintiunBloques(
	t *testing.T,
) {
	t.Parallel()
	preimagen, err := hex.DecodeString(preimagenMaterialPostgreSQLV3Hex)
	if err != nil || len(preimagen) != 2992 {
		t.Fatalf("preimagen congelada inválida: bytes=%d error=%v", len(preimagen), err)
	}
	esperada, _ := hex.DecodeString(huellaMaterialPostgreSQLV3)
	posicion := 0
	for bloque := 0; bloque < 21; bloque++ {
		if posicion+8 > len(preimagen) {
			t.Fatalf("prefijo truncado en bloque %d", bloque)
		}
		longitud := binary.BigEndian.Uint64(preimagen[posicion : posicion+8])
		inicioPrefijo := posicion
		posicion += 8
		if longitud > uint64(len(preimagen)-posicion) {
			t.Fatalf("contenido truncado en bloque %d", bloque)
		}
		inicioContenido := posicion
		posicion += int(longitud)
		for nombre, indice := range map[string]int{
			"longitud":  inicioPrefijo + 7,
			"contenido": inicioContenido,
		} {
			mutada := bytes.Clone(preimagen)
			mutada[indice] ^= 1
			suma := sha256.Sum256(mutada)
			if bytes.Equal(suma[:], esperada) {
				t.Fatalf("mutación %s del bloque %d no ligada", nombre, bloque)
			}
		}
	}
	if posicion != len(preimagen) {
		t.Fatalf("bytes residuales en preimagen: %d", len(preimagen)-posicion)
	}
}
