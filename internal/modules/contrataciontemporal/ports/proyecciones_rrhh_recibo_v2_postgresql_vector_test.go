func TestVectoresPostgreSQLCanonReciboLecturaRRHHV2(t *testing.T) {
	for _, vector := range []struct {
		nombre      string
		preparar    func(*testing.T, string) ports.ReciboLecturaRRHH
		canonHex    string
		selloSHA256 string
	}{
		{
			nombre:      "detalle_génesis",
			preparar:    reciboDetalleGenesisVectorPostgreSQL,
			canonHex:    canonReciboPostgreSQLV2HexDetalleGenesis,
			selloSHA256: selloReciboPostgreSQLV2DetalleGenesis,
		},
		{
			nombre:      "cuadro_encadenado",
			preparar:    reciboCuadroEncadenadoVectorPostgreSQL,
			canonHex:    canonReciboPostgreSQLV2HexCuadroCadena,
			selloSHA256: selloReciboPostgreSQLV2CuadroCadena,
		},
	} {
		t.Run(vector.nombre, func(t *testing.T) {
			// El fixture entra por A4.3, conservando motivo, correlación y
			// material atestado del vector publicado; ningún campo canónico cambia.
			recibo := vector.preparar(t, vector.selloSHA256)
			canon, err :=
				ports.ExportarCanonReciboLecturaRRHHV2ParaVectorPostgreSQL(
					recibo,
				)
			if err != nil {
				t.Fatal(err)
			}
			suma := sha256.Sum256(canon)
			obtenidoHex := hex.EncodeToString(canon)
			obtenidoSello := hex.EncodeToString(suma[:])
			if obtenidoHex != vector.canonHex ||
				obtenidoSello != vector.selloSHA256 {
				t.Fatalf(
					"vector recibo PostgreSQL cambió: canon=%s sello=%s",
					obtenidoHex,
					obtenidoSello,
				)
			}
		})
	}
}

func reciboDetalleGenesisVectorPostgreSQL(
	t *testing.T,
	sello string,
) ports.ReciboLecturaRRHH {
	t.Helper()
	datosDetalle := datosDetalleMinimizadoPrueba(3)
	entrada := construirEntradaDetalleMinimizadaPrueba(t, datosDetalle)
	instante := instantePuertosRRHH()
	_, contexto := autoridadYContextoPuertosRRHH(t, instante)
	solicitud, err := ports.NuevaSolicitudDetalleRRHH(
		datosDetalle.resumen.ExpedienteRef,
		datosDetalle.resumen.Version,
	)
	if err != nil {
		t.Fatal(err)
	}
	capacidad := capacidadDetallePuertosRRHH(
		t, contexto, solicitud, instante,
	)
	generada := instante.Add(time.Second)
	contenido, err := entrada.ExportarContenidoCanonicoParaSQL(generada)
	if err != nil {
		t.Fatal(err)
	}
	resultado, err := contenido.ExportarResultadoCanonicoParaSQL()
	if err != nil {
		t.Fatal(err)
	}
	datos := datosReciboCuadroV2Prueba{
		contexto: contexto, capacidad: capacidad,
		accesoRef: "acceso:rrhh:f996e98f214fcc5c252569b61e95bb8c",
		secuencia: 1, anterior: strings.Repeat("0", 64),
		huella:  strings.Repeat("2", 64),
		vinculo: strings.Repeat("3", 64),
		alcance: "", registradaEn: generada.Add(time.Second),
		auditoriaRef:    "auditoria:vec:detalle:vector-pg",
		auditoriaHuella: strings.Repeat("a", 64),
		consumoHuella:   strings.Repeat("d", 64),
		contenidoHuella: resultado.ContenidoHuellaSHA256(),
		resultadoHuella: resultado.HuellaSHA256(),
		cursorHuella:    "", generadaEn: generada,
		expedienteRef: datosDetalle.resumen.ExpedienteRef,
		version:       datosDetalle.resumen.Version, total: 1,
	}
	if sello == "" {
		sello = selloCanonReciboV2Prueba(datos)
	}
	registro, evidencia := nominalesReciboCuadroV2Prueba(t, datos)
	recibo, err := ports.NuevoReciboLecturaRRHHV2(
		contexto, capacidad, registro, evidencia, sello,
	)
	if err != nil {
		t.Fatalf("construir Recibo V2 de detalle génesis: %v", err)
	}
	return recibo
}

