func TestVectoresPostgreSQLCanonReciboLecturaRRHHV2(t *testing.T) {
	t.Parallel()
	for _, vector := range []struct {
		nombre      string
		secuencia   uint64
		anterior    string
		alcance     string
		expediente  string
		version     uint64
		total       uint16
		cursor      string
		canonHex    string
		selloSHA256 string
	}{
		{
			nombre: "génesis", secuencia: 1,
			anterior: strings.Repeat("0", 64),
			alcance:  strings.Repeat("7", 64),
			total:    2, cursor: strings.Repeat("e", 64),
			canonHex:    canonReciboPostgreSQLV2HexGenesis,
			selloSHA256: selloReciboPostgreSQLV2Genesis,
		},
		{
			nombre: "encadenado", secuencia: 2,
			anterior:   strings.Repeat("d", 64),
			expediente: "expediente:rrhh:vector-pg", version: 4,
			total: 1, canonHex: canonReciboPostgreSQLV2HexCadena,
			selloSHA256: selloReciboPostgreSQLV2Cadena,
		},
	} {
		t.Run(vector.nombre, func(t *testing.T) {
			recibo := reciboLecturaRRHHV2VectorPostgreSQL(
				vector.secuencia,
				vector.anterior,
				vector.alcance,
				vector.expediente,
				vector.version,
				vector.total,
				vector.cursor,
			)
			canon, err := recibo.canonReciboLecturaRRHHV2()
			if err != nil {
				t.Fatal(err)
			}
			suma := sha256.Sum256(canon)
			obtenidoHex := hex.EncodeToString(canon)
			obtenidoSello := hex.EncodeToString(suma[:])
			if obtenidoHex != vector.canonHex ||
				obtenidoSello != vector.selloSHA256 {
				t.Fatalf(
					"vector recibo PostgreSQL cambió: canon=%s sello=%s",
					obtenidoHex,
					obtenidoSello,
				)
			}
		})
	}
}

func reciboLecturaRRHHV2VectorPostgreSQL(
	secuencia uint64,
	anterior string,
	alcance string,
	expediente string,
	version uint64,
	total uint16,
	cursor string,
) ReciboLecturaRRHH {
	registrada := time.Date(2026, 7, 28, 9, 10, 12, 654321000, time.UTC)
	generada := registrada.Add(-time.Second)
	registro := ResultadoRegistradorAccesoRRHHV2{
		esquema:                      EsquemaResultadoRegistradorAccesoRRHHV2,
		accesoRef:                    "acceso:rrhh:0123456789abcdef0123456789abcdef",
		secuencia:                    secuencia,
		anteriorSHA256:               anterior,
		huellaSHA256:                 strings.Repeat("a", 64),
		vinculoIdentidadHuellaSHA256: strings.Repeat("b", 64),
		alcanceHuellaSHA256:          alcance,
		registradaEn:                 registrada,
	}
	evidencia := EvidenciaConsumoResultadoRRHHV2{
		auditoriaRef:          "auditoria:rrhh:vector-pg",
		auditoriaHuellaSHA256: strings.Repeat("c", 64),
		consumoHuellaSHA256:   strings.Repeat("d", 64),
		contenidoHuellaSHA256: strings.Repeat("1", 64),
		resultadoHuellaSHA256: strings.Repeat("2", 64),
		cursorHuellaSHA256:    cursor,
		generadaEn:            generada,
		expedienteRef:         expediente,
		version:               version,
		total:                 total,
	}
	return ReciboLecturaRRHH{
		registroV2:              registro,
		evidenciaV2:             evidencia,
		decisionRef:             "decision:rrhh:vector-pg",
		decisionHuella:          strings.Repeat("3", 64),
		capacidadHuella:         strings.Repeat("4", 64),
		materialHuella:          strings.Repeat("5", 64),
		consultaHuella:          strings.Repeat("6", 64),
		correlacionRef:          "correlacion:rrhh:vector-pg",
		autenticacionRefV2:      "autenticacion:rrhh:vector-pg",
		autenticacionHuellaV2:   strings.Repeat("7", 64),
		sesionRef:               "sesion:rrhh:vector-pg",
		controlSesionRefV2:      "control:sesion:rrhh:vector-pg",
		controlSesionRevisionV2: 5,
		controlSesionHuellaV2:   strings.Repeat("8", 64),
		actorRefV2:              "actor:rrhh:vector-pg",
		perfilRefV2:             "perfil:rrhh:vector-pg",
		perfilVersionV2:         6,
		organizacionRef:         "organizacion:diputacion-granada",
		claseAmbito: func() ClaseAmbitoConsultaRRHH {
			if expediente == "" {
				return AmbitoCentroRRHH
			}
			return AmbitoOrganizacionRRHH
		}(),
		ambitoRef: func() string {
			if expediente == "" {
				return "centro:rrhh:vector-pg"
			}
			return "organizacion:diputacion-granada"
		}(),
		accion: func() string {
			if expediente == "" {
				return AccionConsultarCuadroRRHH
			}
			return AccionConsultarDetalleRRHH
		}(),
		finalidad: func() string {
			if expediente == "" {
				return FinalidadConsultarCuadroRRHH
			}
			return FinalidadConsultarDetalleRRHH
		}(),
	}
}
